/**
 * Emit `dist/_redirects` for the Netlify deploy.
 *
 * ## Why this is generated and not written into netlify.toml
 *
 * Netlify does not interpolate environment variables into `netlify.toml`, so a
 * proxy target written there is a hard-coded hostname in git — which means a
 * deploy preview aimed at a stage API cannot be had without editing the file
 * every project shares. `API_ORIGIN` is a Netlify environment variable instead,
 * and this writes the two rules that read it.
 *
 * ## Why an unset API_ORIGIN fails the build
 *
 * The SPA is served with a catch-all rewrite to `index.html`, which is what
 * makes client-side routing work. Without the proxy rules in front of it,
 * `GET /api/auth/me` does not 404 — it returns the SPA's own HTML with a 200.
 * `useSession` then parses HTML as JSON, the session is never established, and
 * the app presents as a permanent login screen with nothing in the console that
 * names the cause. A build that stops is a far cheaper failure than a site that
 * loads and cannot sign anybody in.
 *
 * ## Why the API is proxied rather than called cross-origin
 *
 * The session is a cookie the API sets on its own origin (08 §9). Rewriting
 * keeps `/api` and `/auth` on the SPA's origin, so `SameSite=Lax` behaves in
 * production exactly as it does behind Vite's dev proxy — and the OIDC chain,
 * which is top-level redirects through the tenant and back, lands on the origin
 * the browser started from. Pointing the SPA at the Render hostname directly
 * would need `SameSite=None` and a CORS allowance, and would send the session
 * cookie on every third-party request the browser makes to that host.
 */

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url)); // apps/web/scripts
const outFile = join(here, "..", "dist", "_redirects");

const origin = process.env["API_ORIGIN"]?.trim();

if (origin === undefined || origin === "") {
  console.error(
    "\nAPI_ORIGIN is not set.\n\n" +
      "It is the public origin of the API service, with a scheme and no\n" +
      "trailing slash — for example https://nusantara-api.onrender.com\n\n" +
      "Set it in Netlify under Site configuration -> Environment variables.\n" +
      "Without it the SPA builds and deploys, and then cannot sign anybody in:\n" +
      "every /api call falls through to the catch-all and returns index.html.\n",
  );
  process.exit(1);
}

let parsed;
try {
  parsed = new URL(origin);
} catch {
  console.error(`API_ORIGIN is not a URL: ${JSON.stringify(origin)}`);
  process.exit(1);
}

if (parsed.protocol !== "https:") {
  // The session cookie is `Secure` unless SESSION_COOKIE_INSECURE=1, so an
  // http: target cannot carry a session at all. Refusing here names the cause;
  // allowing it produces the same silent login loop as an unset origin.
  console.error(`API_ORIGIN must be https — got ${parsed.protocol}//`);
  process.exit(1);
}

const base = origin.replace(/\/+$/, "");

const body = `# Generated by apps/web/scripts/netlify-redirects.mjs — do not edit.
# API_ORIGIN=${base}

# The API and the OIDC endpoints, proxied so they stay on this origin and the
# session cookie behaves as it does behind Vite's dev proxy. 200 is what makes
# it a rewrite rather than a redirect the browser follows.
/api/*   ${base}/api/:splat   200
/auth/*  ${base}/auth/:splat  200

# Client-side routing. Last, so it cannot shadow the two rules above.
/*       /index.html          200
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, body, "utf8");
console.log(`wrote ${outFile}\n${body}`);
